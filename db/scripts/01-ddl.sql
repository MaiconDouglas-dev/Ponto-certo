-- ---------------------------------------------------------------------
-- 1) USUARIO  (cuidador, motorista, gestor)
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nome             VARCHAR2(120)  NOT NULL,
    email            VARCHAR2(160)  NOT NULL,          -- gravar sempre em minusculas
    senha_hash       VARCHAR2(100)  NOT NULL,          -- BCrypt (60 chars), nunca senha pura
    perfil           VARCHAR2(10)   NOT NULL,
    expo_push_token  VARCHAR2(200),                    -- token do Expo Push (RF14)
    criado_em        TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_usuario        PRIMARY KEY (id),
    CONSTRAINT uq_usuario_email  UNIQUE (email),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('CUIDADOR','MOTORISTA','GESTOR'))
);

-- ---------------------------------------------------------------------
-- 2) PARADA
-- ---------------------------------------------------------------------
CREATE TABLE parada (
    id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    codigo_sptrans   NUMBER(10)     NOT NULL,          -- campo "cp" da Olho Vivo
    nome             VARCHAR2(150)  NOT NULL,
    endereco         VARCHAR2(250),
    latitude         NUMBER(9,6),
    longitude        NUMBER(9,6),
    CONSTRAINT pk_parada        PRIMARY KEY (id),
    CONSTRAINT uq_parada_codigo UNIQUE (codigo_sptrans)
);

-- ---------------------------------------------------------------------
-- 3) LINHA
-- ---------------------------------------------------------------------
CREATE TABLE linha (
    id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    codigo_sptrans   NUMBER(10)     NOT NULL,          -- campo "cl" da Olho Vivo
    letreiro         VARCHAR2(20)   NOT NULL,          -- ex.: 6091-10
    sentido          NUMBER(1)      NOT NULL,          -- 1 = principal->secundario, 2 = inverso
    destino          VARCHAR2(120),                    -- ex.: Terminal Varginha (usado na voz)
    CONSTRAINT pk_linha         PRIMARY KEY (id),
    CONSTRAINT uq_linha_codigo  UNIQUE (codigo_sptrans),
    CONSTRAINT ck_linha_sentido CHECK (sentido IN (1,2))
);

-- ---------------------------------------------------------------------
-- 4) PASSAGEIRO (passageiro assistido)
--    Dado sensivel (deficiencia): so o tipo de necessidade + consentimento do cuidador.
-- ---------------------------------------------------------------------
CREATE TABLE passageiro (
    id                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    cuidador_id         NUMBER         NOT NULL,
    nome                VARCHAR2(120)  NOT NULL,
    tipo_necessidade    VARCHAR2(20)   NOT NULL,
    contato_emergencia  VARCHAR2(40)   NOT NULL,
    consentimento_em    TIMESTAMP      NOT NULL,       -- LGPD: quando o cuidador aceitou o termo
    versao_termo        VARCHAR2(20)   NOT NULL,       -- LGPD: qual versao do termo foi aceita
    criado_em           TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_passageiro PRIMARY KEY (id),
    CONSTRAINT fk_passageiro_cuidador FOREIGN KEY (cuidador_id)
        REFERENCES usuario (id) ON DELETE CASCADE,     -- excluir cuidador apaga seus passageiros
    CONSTRAINT ck_passageiro_necessidade CHECK (tipo_necessidade IN
        ('CADEIRA_DE_RODAS','BAIXA_VISAO','MOBILIDADE_REDUZIDA','IDOSO'))
);

-- ---------------------------------------------------------------------
-- 5) CARTAO (Bilhete Unico). Guarda so o HASH do UID.
--    Dica: calcular HMAC-SHA256 com segredo (variavel de ambiente) na aplicacao.
--    SHA-256 puro do UID (4 bytes) e facil de quebrar por forca bruta.
-- ---------------------------------------------------------------------
CREATE TABLE cartao (
    id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    passageiro_id    NUMBER         NOT NULL,
    uid_hash         CHAR(64)       NOT NULL,
    ativo            NUMBER(1)      DEFAULT 1 NOT NULL,
    criado_em        TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_cartao PRIMARY KEY (id),
    CONSTRAINT uq_cartao_uid UNIQUE (uid_hash),        -- cartao ja vinculado a outro passageiro
    CONSTRAINT fk_cartao_passageiro FOREIGN KEY (passageiro_id)
        REFERENCES passageiro (id) ON DELETE CASCADE,
    CONSTRAINT ck_cartao_ativo CHECK (ativo IN (0,1))
);

-- ---------------------------------------------------------------------
-- 6) ROTA_FREQUENTE (parada de origem + linha, ligada ao passageiro)
-- ---------------------------------------------------------------------
CREATE TABLE rota_frequente (
    id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    passageiro_id    NUMBER         NOT NULL,
    parada_id        NUMBER         NOT NULL,
    linha_id         NUMBER         NOT NULL,
    apelido          VARCHAR2(60),                     -- ex.: Casa -> UBS
    CONSTRAINT pk_rota_frequente PRIMARY KEY (id),
    CONSTRAINT uq_rota_pass_parada_linha UNIQUE (passageiro_id, parada_id, linha_id),
    CONSTRAINT fk_rota_passageiro FOREIGN KEY (passageiro_id)
        REFERENCES passageiro (id) ON DELETE CASCADE,
    CONSTRAINT fk_rota_parada FOREIGN KEY (parada_id) REFERENCES parada (id),
    CONSTRAINT fk_rota_linha  FOREIGN KEY (linha_id)  REFERENCES linha (id)
);

-- ---------------------------------------------------------------------
-- 7) TOTEM (dispositivo ESP32 da parada)
-- ---------------------------------------------------------------------
CREATE TABLE totem (
    id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    parada_id        NUMBER         NOT NULL,
    identificador    VARCHAR2(30)   NOT NULL,          -- ex.: TOTEM-0001
    token_hash       CHAR(64)       NOT NULL,          -- hash do token do dispositivo (JWT/segredo)
    status           VARCHAR2(10)   DEFAULT 'ATIVO' NOT NULL,
    ultimo_sinal_em  TIMESTAMP,
    criado_em        TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_totem PRIMARY KEY (id),
    CONSTRAINT uq_totem_identificador UNIQUE (identificador),
    CONSTRAINT fk_totem_parada FOREIGN KEY (parada_id) REFERENCES parada (id),
    CONSTRAINT ck_totem_status CHECK (status IN ('ATIVO','INATIVO'))
);

-- ---------------------------------------------------------------------
-- 8) VEICULO (onibus)
--    Simplificacao do MVP: 1 veiculo = 1 linha fixa e 1 motorista fixo.
-- ---------------------------------------------------------------------
CREATE TABLE veiculo (
    id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    prefixo          VARCHAR2(10)   NOT NULL,          -- campo "p" da Olho Vivo
    linha_id         NUMBER         NOT NULL,
    motorista_id     NUMBER,
    CONSTRAINT pk_veiculo PRIMARY KEY (id),
    CONSTRAINT uq_veiculo_prefixo   UNIQUE (prefixo),
    CONSTRAINT uq_veiculo_motorista UNIQUE (motorista_id),  -- motorista em 1 veiculo por vez
    CONSTRAINT fk_veiculo_linha FOREIGN KEY (linha_id) REFERENCES linha (id),
    CONSTRAINT fk_veiculo_motorista FOREIGN KEY (motorista_id)
        REFERENCES usuario (id) ON DELETE SET NULL
);

-- ---------------------------------------------------------------------
-- 9) SOLICITACAO_EMBARQUE (entidade central)
--    passageiro_id e linha_id sao opcionais (botao sem cartao).
--    Excluir passageiro NAO apaga a solicitacao: ela fica anonima (passageiro_id NULL),
--    preservando indicadores e auditoria sem dado pessoal.
-- ---------------------------------------------------------------------
CREATE TABLE solicitacao_embarque (
    id                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    passageiro_id       NUMBER,
    totem_id            NUMBER         NOT NULL,
    linha_id            NUMBER,
    tipo_sinal          VARCHAR2(10)   NOT NULL,
    status              VARCHAR2(20)   DEFAULT 'CRIADA' NOT NULL,
    chave_idempotencia  VARCHAR2(80)   NOT NULL,
    mensagem_voz        VARCHAR2(300),
    criada_em           TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    atualizada_em       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_solicitacao PRIMARY KEY (id),
    CONSTRAINT uq_solicitacao_chave UNIQUE (chave_idempotencia),  -- ultima barreira (RNF02)
    CONSTRAINT fk_solic_passageiro FOREIGN KEY (passageiro_id)
        REFERENCES passageiro (id) ON DELETE SET NULL,
    CONSTRAINT fk_solic_totem FOREIGN KEY (totem_id) REFERENCES totem (id),
    CONSTRAINT fk_solic_linha FOREIGN KEY (linha_id) REFERENCES linha (id),
    CONSTRAINT ck_solic_tipo_sinal CHECK (tipo_sinal IN ('CARTAO','BOTAO')),
    CONSTRAINT ck_solic_status CHECK (status IN
        ('CRIADA','MOTORISTA_AVISADO','EMBARCADO','NAO_ATENDIDA','SEM_ONIBUS','CANCELADA'))
);

-- Regra: um passageiro so pode ter UMA solicitacao ativa.
-- Indice unico baseado em funcao: so entra na unicidade quem esta ativo e tem passageiro.
-- NAO_ATENDIDA e transitoria (aguarda o proximo onibus) e conta como ativa.
-- Estados finais (fora do indice): EMBARCADO, SEM_ONIBUS, CANCELADA.
-- Regra do prazo (implementada em prc_atualizar_status): a janela e de 40 minutos
-- contados a partir de criada_em. Se, ao procurar o proximo onibus, nenhum estiver
-- previsto dentro dessa janela, a solicitacao vai para SEM_ONIBUS.
-- CANCELADA fica para o cancelamento feito pelo proprio passageiro (segundo toque).
CREATE UNIQUE INDEX uq_solic_passageiro_ativa ON solicitacao_embarque (
    CASE WHEN status IN ('CRIADA','MOTORISTA_AVISADO','NAO_ATENDIDA')
         THEN passageiro_id END
);

-- ---------------------------------------------------------------------
-- 10) SINAL_TOTEM (cada sinal ACEITO de cartao/botao; heartbeat fica so no MongoDB)
--     Serve a API .NET (idempotencia) e permite o relatorio "totens com
--     muitos sinais por minuto" ter equivalente no Oracle.
-- ---------------------------------------------------------------------
CREATE TABLE sinal_totem (
    id                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    totem_id            NUMBER         NOT NULL,
    chave_idempotencia  VARCHAR2(80)   NOT NULL,
    tipo                VARCHAR2(10)   NOT NULL,
    uid_hash            CHAR(64),
    solicitacao_id      NUMBER,                        -- preenchido quando a API Java processa
    recebido_em         TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_sinal_totem PRIMARY KEY (id),
    CONSTRAINT uq_sinal_chave UNIQUE (chave_idempotencia),
    CONSTRAINT fk_sinal_totem FOREIGN KEY (totem_id) REFERENCES totem (id),
    CONSTRAINT fk_sinal_solicitacao FOREIGN KEY (solicitacao_id)
        REFERENCES solicitacao_embarque (id) ON DELETE SET NULL,
    CONSTRAINT ck_sinal_tipo CHECK (tipo IN ('CARTAO','BOTAO')),
    CONSTRAINT ck_sinal_uid CHECK (tipo = 'BOTAO' OR uid_hash IS NOT NULL)
);

-- ---------------------------------------------------------------------
-- 11) TENTATIVA_EMBARQUE (cada tentativa de atendimento por um onibus)
--     Separa a solicitacao original das tentativas feitas pelos onibus.
--     veiculo_id NULL = previsao falhou e o alerta foi para a linha toda (RNF10).
--     motorista_id e gravado na tentativa porque VEICULO.motorista_id muda com o tempo.
--     resultado: PENDENTE (alerta enviado, aguardando), EMBARCADO (motorista confirmou),
--                NAO_ATENDIDA (onibus passou), CANCELADA (pedido cancelado/expirado antes).
-- ---------------------------------------------------------------------
CREATE TABLE tentativa_embarque (
    id                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    solicitacao_id    NUMBER         NOT NULL,
    linha_id          NUMBER         NOT NULL,
    veiculo_id        NUMBER,
    motorista_id      NUMBER,
    previsao_chegada  TIMESTAMP,                       -- NULL se Olho Vivo/ML nao responderam
    alertado_em       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    resultado         VARCHAR2(15)   DEFAULT 'PENDENTE' NOT NULL,
    confirmado_em     TIMESTAMP,                       -- so quando resultado = EMBARCADO
    CONSTRAINT pk_tentativa PRIMARY KEY (id),
    CONSTRAINT fk_tentativa_solicitacao FOREIGN KEY (solicitacao_id)
        REFERENCES solicitacao_embarque (id) ON DELETE CASCADE,
    CONSTRAINT fk_tentativa_linha     FOREIGN KEY (linha_id)     REFERENCES linha (id),
    CONSTRAINT fk_tentativa_veiculo   FOREIGN KEY (veiculo_id)   REFERENCES veiculo (id),
    CONSTRAINT fk_tentativa_motorista FOREIGN KEY (motorista_id)
        REFERENCES usuario (id) ON DELETE SET NULL,
    CONSTRAINT ck_tentativa_resultado CHECK (resultado IN
        ('PENDENTE','EMBARCADO','NAO_ATENDIDA','CANCELADA')),
    CONSTRAINT ck_tentativa_confirmado CHECK (
        (resultado = 'EMBARCADO' AND confirmado_em IS NOT NULL)
        OR (resultado <> 'EMBARCADO' AND confirmado_em IS NULL))
);

-- ---------------------------------------------------------------------
-- 12) AUDITORIA_SOLICITACAO (preenchida pelo gatilho trg_auditoria_solicitacao)
--     SEM chave estrangeira de proposito: o gatilho de DELETE grava a linha de
--     auditoria no mesmo instante em que a solicitacao some; com FK isso falharia.
-- ---------------------------------------------------------------------
CREATE TABLE auditoria_solicitacao (
    id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    solicitacao_id   NUMBER         NOT NULL,
    operacao         VARCHAR2(6)    NOT NULL,
    status_antigo    VARCHAR2(20),
    status_novo      VARCHAR2(20),
    usuario_banco    VARCHAR2(60)   NOT NULL,
    data_hora        TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_auditoria PRIMARY KEY (id),
    CONSTRAINT ck_auditoria_operacao CHECK (operacao IN ('INSERT','UPDATE','DELETE'))
);

-- ---------------------------------------------------------------------
