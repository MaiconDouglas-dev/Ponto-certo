-- ---------------------------------------------------------------------
-- 1) USUARIO
-- ---------------------------------------------------------------------
CREATE TABLE USUARIO (
    ID               INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME             VARCHAR2 (80 CHAR)   NOT NULL,
    EMAIL            VARCHAR2 (60 CHAR)   NOT NULL,
    SENHA_HASH       VARCHAR2 (160 CHAR)  NOT NULL,
    PERFIL           VARCHAR2 (10 CHAR)   NOT NULL,
    EXPO_PUSH_TOKEN  VARCHAR2 (200 CHAR),
    CRIADO_EM        TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USUARIO        PRIMARY KEY (ID),
    CONSTRAINT UN_EMAIL          UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIO_PERFIL CHECK (PERFIL IN ('CUIDADOR','MOTORISTA','GESTOR'))
);

-- ---------------------------------------------------------------------
-- 2) PARADA
-- ---------------------------------------------------------------------
CREATE TABLE PARADA (
    ID               INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CODIGO_SPTRANS   NUMBER (10)          NOT NULL,
    NOME             VARCHAR2 (120 CHAR)  NOT NULL,
    ENDERECO         VARCHAR2 (200 CHAR),
    LATITUDE         NUMBER (9,6),
    LONGITUDE        NUMBER (9,6),
    CONSTRAINT PK_PARADA        PRIMARY KEY (ID),
    CONSTRAINT UN_PARADA_CODIGO UNIQUE (CODIGO_SPTRANS)
);

-- ---------------------------------------------------------------------
-- 3) LINHA
-- ---------------------------------------------------------------------
CREATE TABLE LINHA (
    ID               INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CODIGO_SPTRANS   NUMBER (10)          NOT NULL,
    LETREIRO         VARCHAR2 (20 CHAR)   NOT NULL,
    SENTIDO          NUMBER (1)           NOT NULL,
    DESTINO          VARCHAR2 (150 CHAR),
    CONSTRAINT PK_LINHA          PRIMARY KEY (ID),
    CONSTRAINT UN_CODIGO_SPTRANS UNIQUE (CODIGO_SPTRANS),
    CONSTRAINT CK_LINHA_SENTIDO  CHECK (SENTIDO IN (1,2))
);

-- ---------------------------------------------------------------------
-- 4) PASSAGEIRO
-- ---------------------------------------------------------------------
CREATE TABLE PASSAGEIRO (
    ID                  INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME                VARCHAR2 (120 CHAR)  NOT NULL,
    TIPO_NECESSIDADE    VARCHAR2 (20 CHAR)   NOT NULL,
    CONTATO_EMERGENCIA  VARCHAR2 (40 CHAR)   NOT NULL,
    CONSENTIMENTO_EM    TIMESTAMP            NOT NULL,
    VERSAO_TERMO        VARCHAR2 (20 CHAR)   NOT NULL,
    CRIADO_EM           TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    CUIDADOR_ID         INTEGER              NOT NULL,
    CONSTRAINT PK_PASSAGEIRO PRIMARY KEY (ID),
    CONSTRAINT FK_PASSAGEIRO_USUARIO FOREIGN KEY (CUIDADOR_ID)
        REFERENCES USUARIO (ID) ON DELETE CASCADE,
    CONSTRAINT CK_PASSAGEIRO_NECESSIDADE CHECK (TIPO_NECESSIDADE IN
        ('CADEIRA_DE_RODAS','BAIXA_VISAO','MOBILIDADE_REDUZIDA','IDOSO'))
);

-- ---------------------------------------------------------------------
-- 5) CARTAO (Bilhete Unico)
-- ---------------------------------------------------------------------
CREATE TABLE CARTAO (
    ID             INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    UID_HASH       CHAR (64 CHAR)  NOT NULL,
    ATIVO          NUMBER (1)      DEFAULT 1 NOT NULL,
    CRIADO_EM      TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    PASSAGEIRO_ID  INTEGER         NOT NULL,
    CONSTRAINT PK_CARTAO PRIMARY KEY (ID),
    CONSTRAINT UN_CARTAO_UID UNIQUE (UID_HASH),
    CONSTRAINT FK_CARTAO_PASSAGEIRO FOREIGN KEY (PASSAGEIRO_ID)
        REFERENCES PASSAGEIRO (ID) ON DELETE CASCADE,
    CONSTRAINT CK_CARTAO_ATIVO CHECK (ATIVO IN (0,1))
);

-- ---------------------------------------------------------------------
-- 6) ROTA_FREQUENTE
-- ---------------------------------------------------------------------
CREATE TABLE ROTA_FREQUENTE (
    ID             INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    APELIDO        VARCHAR2 (60 CHAR),
    PASSAGEIRO_ID  INTEGER  NOT NULL,
    PARADA_ID      INTEGER  NOT NULL,
    LINHA_ID       INTEGER  NOT NULL,
    CONSTRAINT PK_ROTA_FREQUENTE PRIMARY KEY (ID),
    CONSTRAINT UN_ROTA_PASS_PARADA_LINHA UNIQUE (PASSAGEIRO_ID, PARADA_ID, LINHA_ID),
    CONSTRAINT FK_ROTA_FREQUENTE_PASSAGEIRO FOREIGN KEY (PASSAGEIRO_ID)
        REFERENCES PASSAGEIRO (ID) ON DELETE CASCADE,
    CONSTRAINT FK_ROTA_FREQUENTE_PARADA FOREIGN KEY (PARADA_ID) REFERENCES PARADA (ID),
    CONSTRAINT FK_ROTA_FREQUENTE_LINHA  FOREIGN KEY (LINHA_ID)  REFERENCES LINHA (ID)
);

-- ---------------------------------------------------------------------
-- 7) TOTEM
-- ---------------------------------------------------------------------
CREATE TABLE TOTEM (
    ID                  INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME_IDENTIFICADOR  VARCHAR2 (30 CHAR)  NOT NULL,
    TOKEN_HASH          CHAR (64 CHAR)      NOT NULL,
    STATUS              VARCHAR2 (10 CHAR)  DEFAULT 'ATIVO' NOT NULL,
    ULTIMO_SINAL_EM     TIMESTAMP,
    CRIADO_EM           TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    PARADA_ID           INTEGER             NOT NULL,
    CONSTRAINT PK_TOTEM PRIMARY KEY (ID),
    CONSTRAINT UN_TOTEM_IDENTIFICADOR UNIQUE (NOME_IDENTIFICADOR),
    CONSTRAINT FK_TOKEN_PARADA FOREIGN KEY (PARADA_ID) REFERENCES PARADA (ID),
    CONSTRAINT CK_TOTEM_STATUS CHECK (STATUS IN ('ATIVO','INATIVO'))
);

-- ---------------------------------------------------------------------
-- 8) VEICULO
-- ---------------------------------------------------------------------
CREATE TABLE VEICULO (
    ID            INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    PREFIXO       VARCHAR2 (10 CHAR)  NOT NULL,
    LINHA_ID      INTEGER             NOT NULL,
    MOTORISTA_ID  INTEGER,
    CONSTRAINT PK_VEICULO PRIMARY KEY (ID),
    CONSTRAINT UN_VEICULO_PREFIXO UNIQUE (PREFIXO),
    CONSTRAINT FK_VEICULO_LINHA FOREIGN KEY (LINHA_ID) REFERENCES LINHA (ID),
    CONSTRAINT FK_VEICULO_USUARIO FOREIGN KEY (MOTORISTA_ID)
        REFERENCES USUARIO (ID) ON DELETE SET NULL
);

CREATE UNIQUE INDEX VEICULO__IDX ON VEICULO (MOTORISTA_ID);

-- ---------------------------------------------------------------------
-- 9) SOLICITACAO_EMBARQUE
-- ---------------------------------------------------------------------
CREATE TABLE SOLICITACAO_EMBARQUE (
    ID                  INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TIPO_SINAL          VARCHAR2 (10 CHAR)   NOT NULL,
    STATUS              VARCHAR2 (20 CHAR)   DEFAULT 'CRIADA' NOT NULL,
    CHAVE_IDEMPOTENCIA  VARCHAR2 (80 CHAR)   NOT NULL,
    MENSAGEM_VOZ        VARCHAR2 (300 CHAR),
    CRIADA_EM           TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    ATUALIZADA_EM       TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    PASSAGEIRO_ID       INTEGER,
    TOTEM_ID            INTEGER              NOT NULL,
    LINHA_ID            INTEGER,
    CONSTRAINT PK_SOLICITACAO_EMBARQUE PRIMARY KEY (ID),
    CONSTRAINT UN_SOLICITACAO_CHAVE UNIQUE (CHAVE_IDEMPOTENCIA),   -- ultima barreira (RNF02)
    CONSTRAINT FK_SOLIC_EMBARQUE_PASSAGEIRO FOREIGN KEY (PASSAGEIRO_ID)
        REFERENCES PASSAGEIRO (ID) ON DELETE SET NULL,
    CONSTRAINT FK_SOLIC_EMBARQUE_TOTEM FOREIGN KEY (TOTEM_ID) REFERENCES TOTEM (ID),
    CONSTRAINT FK_SOLIC_EMBARQUE_LINHA FOREIGN KEY (LINHA_ID) REFERENCES LINHA (ID),
    CONSTRAINT CK_SOLIC_TIPO_SINAL CHECK (TIPO_SINAL IN ('CARTAO','BOTAO')),
    CONSTRAINT CK_SOLIC_STATUS CHECK (STATUS IN
        ('CRIADA','MOTORISTA_AVISADO','EMBARCADO','NAO_ATENDIDA','SEM_ONIBUS','CANCELADA'))
);

CREATE UNIQUE INDEX UQ_SOLIC_PASSAGEIRO_ATIVA ON SOLICITACAO_EMBARQUE (
    CASE WHEN STATUS IN ('CRIADA','MOTORISTA_AVISADO','NAO_ATENDIDA')
         THEN PASSAGEIRO_ID END
);

-- ---------------------------------------------------------------------
-- 10) SINAL_TOTEM
-- ---------------------------------------------------------------------
CREATE TABLE SINAL_TOTEM (
    ID                       INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CHAVE_IDEMPOTENCIA       VARCHAR2 (80 CHAR)  NOT NULL,
    TIPO                     VARCHAR2 (10 CHAR)  NOT NULL,
    UID_HASH                 CHAR (64 CHAR),
    RECEBIDO_EM              TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    TOTEM_ID                 INTEGER             NOT NULL,
    SOLICITACAO_EMBARQUE_ID  INTEGER,
    CONSTRAINT PK_SINAL_TOTEM PRIMARY KEY (ID),
    CONSTRAINT UN_SINAL_CHAVE UNIQUE (CHAVE_IDEMPOTENCIA),
    CONSTRAINT FK_SINAL_TOTEM_TOTEM FOREIGN KEY (TOTEM_ID) REFERENCES TOTEM (ID),
    CONSTRAINT FK_SINAL_TOTEM_SOLIC_EMBARQUE FOREIGN KEY (SOLICITACAO_EMBARQUE_ID)
        REFERENCES SOLICITACAO_EMBARQUE (ID) ON DELETE SET NULL,
    CONSTRAINT CK_SINAL_TIPO CHECK (TIPO IN ('CARTAO','BOTAO')),
    CONSTRAINT CK_SINAL_UID CHECK (TIPO = 'BOTAO' OR UID_HASH IS NOT NULL)
);

-- ---------------------------------------------------------------------
-- 11) TENTATIVA_EMBARQUE
-- ---------------------------------------------------------------------
CREATE TABLE TENTATIVA_EMBARQUE (
    ID                       INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    PREVISAO_CHEGADA         TIMESTAMP,
    ALERTADO_EM              TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    RESULTADO                VARCHAR2 (15 CHAR)  DEFAULT 'PENDENTE' NOT NULL,
    CONFIRMADO_EM            TIMESTAMP,
    SOLICITACAO_EMBARQUE_ID  INTEGER             NOT NULL,
    LINHA_ID                 INTEGER             NOT NULL,
    VEICULO_ID               INTEGER,
    USUARIO_ID               INTEGER,
    CONSTRAINT PK_TENTATIVA_EMBARQUE PRIMARY KEY (ID),
    CONSTRAINT FK_TENTATIVA_EMB_SOLIC_EMB FOREIGN KEY (SOLICITACAO_EMBARQUE_ID)
        REFERENCES SOLICITACAO_EMBARQUE (ID) ON DELETE CASCADE,
    CONSTRAINT FK_TENTATIVA_EMBARQUE_LINHA   FOREIGN KEY (LINHA_ID)   REFERENCES LINHA (ID),
    CONSTRAINT FK_TENTATIVA_EMBARQUE_VEICULO FOREIGN KEY (VEICULO_ID) REFERENCES VEICULO (ID),
    CONSTRAINT FK_TENTATIVA_EMBARQUE_USUARIO FOREIGN KEY (USUARIO_ID)
        REFERENCES USUARIO (ID) ON DELETE SET NULL,
    CONSTRAINT CK_TENTATIVA_RESULTADO CHECK (RESULTADO IN
        ('PENDENTE','EMBARCADO','NAO_ATENDIDA','CANCELADA')),
    CONSTRAINT CK_TENTATIVA_CONFIRMADO CHECK (
        (RESULTADO = 'EMBARCADO' AND CONFIRMADO_EM IS NOT NULL)
        OR (RESULTADO <> 'EMBARCADO' AND CONFIRMADO_EM IS NULL))
);

-- ---------------------------------------------------------------------
-- 12) AUDITORIA_SOLICITACAO
-- ---------------------------------------------------------------------
CREATE TABLE AUDITORIA_SOLICITACAO (
    ID              INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    SOLICITACAO_ID  INTEGER             NOT NULL,
    OPERACAO        VARCHAR2 (6 CHAR)   NOT NULL,
    STATUS_ANTIGO   VARCHAR2 (20 CHAR),
    STATUS_NOVO     VARCHAR2 (20 CHAR),
    USUARIO_BANCO   VARCHAR2 (60 CHAR)  NOT NULL,
    DATA_HORA       TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_AUDITORIA_SOLICITACAO PRIMARY KEY (ID),
    CONSTRAINT CK_AUDITORIA_OPERACAO CHECK (OPERACAO IN ('INSERT','UPDATE','DELETE'))
);

-- ---------------------------------------------------------------------
-- 13) INDICES DE CHAVE ESTRANGEIRA E DE CONSULTA
-- ---------------------------------------------------------------------
CREATE INDEX IDX_PASSAGEIRO_CUIDADOR   ON PASSAGEIRO (CUIDADOR_ID);
CREATE INDEX IDX_CARTAO_PASSAGEIRO     ON CARTAO (PASSAGEIRO_ID);
CREATE INDEX IDX_ROTA_PARADA           ON ROTA_FREQUENTE (PARADA_ID);
CREATE INDEX IDX_ROTA_LINHA            ON ROTA_FREQUENTE (LINHA_ID);
CREATE INDEX IDX_TOTEM_PARADA          ON TOTEM (PARADA_ID);
CREATE INDEX IDX_VEICULO_LINHA         ON VEICULO (LINHA_ID);
CREATE INDEX IDX_SOLIC_TOTEM           ON SOLICITACAO_EMBARQUE (TOTEM_ID);
CREATE INDEX IDX_SOLIC_LINHA           ON SOLICITACAO_EMBARQUE (LINHA_ID);
CREATE INDEX IDX_SOLIC_PASSAGEIRO      ON SOLICITACAO_EMBARQUE (PASSAGEIRO_ID);
CREATE INDEX IDX_SOLIC_STATUS_CRIADA   ON SOLICITACAO_EMBARQUE (STATUS, CRIADA_EM);
CREATE INDEX IDX_SINAL_TOTEM_DATA      ON SINAL_TOTEM (TOTEM_ID, RECEBIDO_EM);
CREATE INDEX IDX_SINAL_SOLICITACAO     ON SINAL_TOTEM (SOLICITACAO_EMBARQUE_ID);
CREATE INDEX IDX_TENTATIVA_SOLIC       ON TENTATIVA_EMBARQUE (SOLICITACAO_EMBARQUE_ID);
CREATE INDEX IDX_TENTATIVA_VEIC_RES    ON TENTATIVA_EMBARQUE (VEICULO_ID, RESULTADO);
CREATE INDEX IDX_TENTATIVA_LINHA_RES   ON TENTATIVA_EMBARQUE (LINHA_ID, RESULTADO);
CREATE INDEX IDX_TENTATIVA_USUARIO     ON TENTATIVA_EMBARQUE (USUARIO_ID);
CREATE INDEX IDX_AUDITORIA_SOLICITACAO ON AUDITORIA_SOLICITACAO (SOLICITACAO_ID, DATA_HORA);

