CREATE INDEX idx_solic_totem           ON solicitacao_embarque (totem_id);
CREATE INDEX idx_solic_linha           ON solicitacao_embarque (linha_id);
CREATE INDEX idx_solic_passageiro      ON solicitacao_embarque (passageiro_id);
CREATE INDEX idx_solic_status_criada   ON solicitacao_embarque (status, criada_em);
CREATE INDEX idx_sinal_totem_data      ON sinal_totem (totem_id, recebido_em);
CREATE INDEX idx_sinal_solicitacao     ON sinal_totem (solicitacao_id);
